/**
 * The Threadlines extension that runs inside every chat Pi process
 * (docs/providers/pi-plan.md, "The Threadlines extension").
 *
 * It has three jobs:
 *
 * 1. Approvals and plan mode, in Pi's `tool_call` hook. Two independent
 *    policies are checked on every call, including calls a tool makes
 *    (codemode's nested calls go through the same hook). Plan mode denies
 *    anything that can change things at every access level. The gate fails
 *    closed: a hook that throws blocks the tool.
 * 2. Threadlines' tools (browser, rooms, pages, commands): a small MCP client
 *    per server registers each tool with `pi.registerTool` as
 *    `mcp__<server>__<tool>`, so calls route back to the server that owns it.
 *    Not Pi's `registerMcpServer`, which disappears when the user turns off
 *    Pi's built-in MCP or names an `mcp.json` server the same.
 * 3. The `/threadlines-mode` command: live access-level and plan-mode changes,
 *    acked as `handled` without starting a run.
 *
 * Settings arrive in the environment (`PI_EXTENSION_ENV`) and are deleted
 * from `process.env` at load, so `bash` children and other extensions never
 * see the tool token. Approval dialogs and the mode command carry a
 * per-process nonce, so nothing else can pose as Threadlines.
 *
 * The source imports nothing at run time: tool schemas are plain JSON Schema,
 * which Pi accepts. It is written to Threadlines' data folder under a name
 * derived from its content, so two Threadlines versions never share a file.
 *
 * @module provider/pi/PiExtensionSource
 */
import { createHash } from "node:crypto";

import { PI_TURN_MARKER_TYPE } from "./PiCursor.ts";
import { PI_EXTENSION_ENV } from "./PiLaunch.ts";

/** The approval dialog's title: `<prefix><nonce>:<JSON PiApprovalRequest>`. */
export const PI_APPROVAL_TITLE_PREFIX = "threadlines-approval:";

/** What the approval dialog asks about; the title carries it as JSON. */
export interface PiApprovalRequest {
  readonly toolCallId: string;
  readonly parentToolCallId?: string;
  readonly toolName: string;
  /** The call's input as JSON, cut to 4,000 characters. */
  readonly input: string;
}

/** The approval dialog's options, answered with `{ value }`. */
export const PI_APPROVAL_OPTIONS = {
  allow: "allow",
  allowForSession: "allow-session",
  deny: "deny",
} as const;

/** The mode command: `/threadlines-mode <nonce> <access> <plan 0|1>`. */
export const PI_MODE_COMMAND = "threadlines-mode";

/** The turn marker command: `/threadlines-turn <nonce> <turnId>` (see `PiCursor`). */
export const PI_TURN_COMMAND = "threadlines-turn";

export const PI_PLAN_MODE_REASON =
  "Plan mode: Threadlines lets Pi read and search only. Describe the change instead of making it.";

/** Prepended to the system prompt while plan mode is on. */
export const PI_PLAN_MODE_INSTRUCTION =
  "Threadlines is in plan mode. Read and search as much as you need, but do not change files, run commands that change anything, or call tools that write. Finish with a concrete plan the user can approve.";

export const PI_EXTENSION_SOURCE = `\
// Threadlines extension for Pi. Generated by Threadlines; edits are replaced.
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

const ENV = ${JSON.stringify(PI_EXTENSION_ENV)};
const APPROVAL_PREFIX = ${JSON.stringify(PI_APPROVAL_TITLE_PREFIX)};
const OPTIONS = ${JSON.stringify(PI_APPROVAL_OPTIONS)};
const MODE_COMMAND = ${JSON.stringify(PI_MODE_COMMAND)};
const TURN_COMMAND = ${JSON.stringify(PI_TURN_COMMAND)};
const TURN_MARKER = ${JSON.stringify(PI_TURN_MARKER_TYPE)};
const PLAN_REASON = ${JSON.stringify(PI_PLAN_MODE_REASON)};
const PLAN_INSTRUCTION = ${JSON.stringify(PI_PLAN_MODE_INSTRUCTION)};
const PROTOCOL = "2025-06-18";
const ACCESS_LEVELS = new Set(["approval-required", "auto-accept-edits", "full-access"]);
// Tools that only read. codemode's own calls are checked one by one.
const READ_TOOLS = new Set(["read", "grep", "find", "ls", "codemode"]);
const EDIT_TOOLS = new Set(["edit", "write"]);

type ToolServer = { name: string; url: string };
type McpTool = {
  name: string;
  description?: string;
  inputSchema?: Record<string, unknown>;
  annotations?: { readOnlyHint?: boolean };
};

function takeEnv(name: string): string | undefined {
  const value = process.env[name];
  delete process.env[name];
  return value && value.length > 0 ? value : undefined;
}

function parseServers(raw: string | undefined): ToolServer[] {
  if (!raw) return [];
  try {
    const value = JSON.parse(raw);
    return Array.isArray(value)
      ? value.filter((s) => s && typeof s.name === "string" && typeof s.url === "string")
      : [];
  } catch {
    return [];
  }
}

function inputSummary(input: unknown): string {
  try {
    return JSON.stringify(input).slice(0, 4000);
  } catch {
    return String(input).slice(0, 4000);
  }
}

function parseRpcBody(body: string, contentType: string): any {
  if (contentType.includes("text/event-stream")) {
    for (const line of body.split("\\n")) {
      const data = line.startsWith("data:") ? line.slice(5).trim() : "";
      if (!data) continue;
      const parsed = JSON.parse(data);
      if (parsed.id !== undefined || parsed.result !== undefined || parsed.error !== undefined) return parsed;
    }
    throw new Error("The tool server sent no answer.");
  }
  return JSON.parse(body);
}

function createClient(url: string, token: string) {
  let nextId = 1;
  let sessionId: string | undefined;
  const headers = () => {
    const next: Record<string, string> = {
      accept: "application/json, text/event-stream",
      authorization: "Bearer " + token,
      "content-type": "application/json",
      "mcp-protocol-version": PROTOCOL,
    };
    if (sessionId) next["mcp-session-id"] = sessionId;
    return next;
  };
  const post = async (payload: unknown, signal?: AbortSignal) => {
    const response = await fetch(url, { method: "POST", headers: headers(), body: JSON.stringify(payload), signal });
    const session = response.headers.get("mcp-session-id");
    if (session) sessionId = session;
    return response;
  };
  const request = async (method: string, params: unknown, signal?: AbortSignal) => {
    const response = await post({ jsonrpc: "2.0", id: nextId++, method, params }, signal);
    const body = await response.text();
    if (!response.ok) throw new Error(method + " failed (" + response.status + "): " + body.slice(0, 300));
    if (!body) return undefined;
    const parsed = parseRpcBody(body, response.headers.get("content-type") ?? "");
    if (parsed.error) throw new Error(parsed.error.message ?? method + " failed");
    return parsed.result;
  };
  return {
    async connect(signal?: AbortSignal) {
      await request("initialize", { protocolVersion: PROTOCOL, capabilities: {}, clientInfo: { name: "threadlines-pi", version: "1" } }, signal);
      await post({ jsonrpc: "2.0", method: "notifications/initialized", params: {} }, signal).catch(() => undefined);
    },
    async listTools(signal?: AbortSignal): Promise<McpTool[]> {
      const tools: McpTool[] = [];
      let cursor: string | undefined;
      do {
        const result: any = await request("tools/list", cursor ? { cursor } : {}, signal);
        tools.push(...(Array.isArray(result?.tools) ? result.tools : []));
        cursor = typeof result?.nextCursor === "string" ? result.nextCursor : undefined;
      } while (cursor);
      return tools;
    },
    callTool(name: string, args: unknown, signal?: AbortSignal) {
      return request("tools/call", { name, arguments: args ?? {} }, signal);
    },
  };
}

function modelContent(result: any) {
  const content: Array<{ type: "text"; text: string } | { type: "image"; data: string; mimeType: string }> = [];
  for (const part of Array.isArray(result?.content) ? result.content : []) {
    if (part?.type === "text" && typeof part.text === "string") content.push({ type: "text", text: part.text });
    else if (part?.type === "image" && typeof part.data === "string" && typeof part.mimeType === "string") {
      content.push({ type: "image", data: part.data, mimeType: part.mimeType });
    }
  }
  if (content.length === 0) content.push({ type: "text", text: JSON.stringify(result?.structuredContent ?? result ?? null) });
  return content;
}

export default async function threadlines(pi: ExtensionAPI) {
  const nonce = takeEnv(ENV.nonce);
  const token = takeEnv(ENV.token);
  const servers = parseServers(takeEnv(ENV.toolServers));
  const initialAccess = takeEnv(ENV.access);
  let access = initialAccess && ACCESS_LEVELS.has(initialAccess) ? initialAccess : "approval-required";
  let plan = takeEnv(ENV.plan) === "1";
  // "Allow for this session", by tool (edits) or by exact call (everything else).
  const grants = new Set<string>();
  const readOnlyTools = new Set<string>();
  const ownTools = new Set<string>();

  pi.on("session_start", () => {
    grants.clear();
  });

  pi.registerCommand(MODE_COMMAND, {
    description: "Set by Threadlines",
    handler: async (args) => {
      const [given, nextAccess, nextPlan] = args.trim().split(/\\s+/);
      if (!nonce || given !== nonce || !ACCESS_LEVELS.has(nextAccess ?? "")) return;
      access = nextAccess as string;
      plan = nextPlan === "1";
    },
  });

  // Marks where a Threadlines turn starts in Pi's own session tree.
  pi.registerCommand(TURN_COMMAND, {
    description: "Set by Threadlines",
    handler: async (args) => {
      const [given, turnId] = args.trim().split(/\\s+/);
      if (!nonce || given !== nonce || !turnId) return;
      pi.appendEntry(TURN_MARKER, { turnId });
    },
  });

  pi.on("before_agent_start", (event) => {
    if (plan) event.systemPromptOptions.sections.threadlines_plan_mode = PLAN_INSTRUCTION;
    else delete event.systemPromptOptions.sections.threadlines_plan_mode;
  });

  pi.on("tool_call", async (event, ctx) => {
    const name = event.toolName;
    const reads =
      READ_TOOLS.has(name) ||
      (name === "tool_search" && pi.getAllTools().some((t) => t.name === name && t.sourceInfo?.path === "builtin:tool-search")) ||
      (ownTools.has(name) && readOnlyTools.has(name));
    if (plan && !reads) return { block: true, reason: PLAN_REASON };
    if (access === "full-access" || reads) return;
    if (access === "auto-accept-edits" && EDIT_TOOLS.has(name)) return;
    const input = inputSummary(event.input);
    const grant = EDIT_TOOLS.has(name) ? name : name + "\\u0000" + input;
    if (grants.has(grant)) return;
    if (!nonce) return { block: true, reason: "Threadlines could not ask for approval." };
    const request = { toolCallId: event.toolCallId, toolName: name, input, ...(event.parentToolCallId ? { parentToolCallId: event.parentToolCallId } : {}) };
    const answer = await ctx.ui.select(
      APPROVAL_PREFIX + nonce + ":" + JSON.stringify(request),
      [OPTIONS.allow, OPTIONS.allowForSession, OPTIONS.deny],
      { signal: ctx.signal },
    );
    if (answer === OPTIONS.allowForSession) {
      grants.add(grant);
      return;
    }
    if (answer === OPTIONS.allow) return;
    return { block: true, reason: name + " was not approved in Threadlines." };
  });

  if (!token || servers.length === 0) return;

  const register = (server: ToolServer, client: ReturnType<typeof createClient>, tools: McpTool[]) => {
    for (const tool of tools) {
      const name = "mcp__" + server.name + "__" + tool.name;
      ownTools.add(name);
      if (tool.annotations?.readOnlyHint === true) readOnlyTools.add(name);
      else readOnlyTools.delete(name);
      pi.registerTool({
        name,
        label: tool.name,
        description: tool.description ?? tool.name,
        parameters: (tool.inputSchema ?? { type: "object", properties: {} }) as never,
        async execute(_toolCallId, params, signal) {
          const result: any = await client.callTool(tool.name, params, signal);
          const content = modelContent(result);
          return {
            content,
            details: { server: server.name, tool: tool.name },
            ...(result?.isError === true ? { isError: true } : {}),
          };
        },
      });
    }
  };

  const started = new Map<string, Promise<void>>();
  const start = (server: ToolServer) => {
    const existing = started.get(server.name);
    if (existing) return existing;
    const attempt = (async () => {
      const client = createClient(server.url, token);
      const signal = AbortSignal.timeout(10000);
      await client.connect(signal);
      register(server, client, await client.listTools(signal));
    })();
    started.set(server.name, attempt);
    void attempt.catch(() => {
      if (started.get(server.name) === attempt) started.delete(server.name);
    });
    return attempt;
  };

  // Registered at load, so Threadlines owns these names before other extensions.
  await Promise.allSettled(servers.map(start));
  pi.on("session_start", async (_event, ctx) => {
    const results = await Promise.allSettled(servers.map(start));
    const failed = results.filter((r) => r.status === "rejected").length;
    if (failed > 0) ctx.ui.notify("Some Threadlines tools are unavailable in this Pi session.", "warning");
  });
}
`;

/** The extension's file name: its content's hash, so versions never collide. */
export function piExtensionFileName(source: string = PI_EXTENSION_SOURCE): string {
  const digest = createHash("sha256").update(source).digest("hex").slice(0, 16);
  return `threadlines-pi-${digest}.ts`;
}

/** Reads a Threadlines approval out of an `extension_ui_request` title, for this process's nonce. */
export function parsePiApprovalTitle(title: string, nonce: string): PiApprovalRequest | undefined {
  const prefix = `${PI_APPROVAL_TITLE_PREFIX}${nonce}:`;
  if (!title.startsWith(prefix)) return undefined;
  try {
    const value = JSON.parse(title.slice(prefix.length)) as Record<string, unknown>;
    if (typeof value.toolCallId !== "string" || typeof value.toolName !== "string")
      return undefined;
    return {
      toolCallId: value.toolCallId,
      toolName: value.toolName,
      input: typeof value.input === "string" ? value.input : "",
      ...(typeof value.parentToolCallId === "string"
        ? { parentToolCallId: value.parentToolCallId }
        : {}),
    };
  } catch {
    return undefined;
  }
}

/** The turn marker command's prompt text. */
export const piTurnCommandText = (input: { readonly nonce: string; readonly turnId: string }) =>
  `/${PI_TURN_COMMAND} ${input.nonce} ${input.turnId}`;

/** The mode command's prompt text, as the adapter sends it. */
export function piModeCommandText(input: {
  readonly nonce: string;
  readonly access: string;
  readonly plan: boolean;
}): string {
  return `/${PI_MODE_COMMAND} ${input.nonce} ${input.access} ${input.plan ? "1" : "0"}`;
}
