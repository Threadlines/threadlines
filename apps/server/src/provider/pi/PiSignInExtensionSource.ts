/**
 * The Threadlines extension that signs Pi in to a model provider, so the
 * user picks a provider and answers Pi's questions in Threadlines instead of
 * in Pi's terminal app (`/login`). It runs only in a short-lived
 * `pi --mode rpc --no-session` that `PiSignIn` starts for one sign-in, never
 * in a chat.
 *
 * Pi 1.3 offers extensions no sign-in API, but the model registry they get
 * wraps Pi's `ModelRuntime`, whose `login` is what `/login` itself calls (with
 * the same questions and events). The extension reaches it there and checks
 * every method it uses first: a Pi without them says `unsupported`, and the
 * user signs in with Pi's own `/login` instead.
 *
 * It talks to Threadlines through Pi's RPC dialogs: a question is a `select`
 * or `input` whose title is `<prefix><nonce>:<JSON question>`, and everything
 * else (the page to open, a device code, progress, the outcome) is a `notify`
 * with the same prefix. The nonce comes in a private file, as the chat
 * extension's does (`PiSecrets`), so no other extension can pose as either
 * side.
 *
 * Pi saves what the user enters in its own `auth.json`. Threadlines keeps no
 * copy.
 *
 * @module provider/pi/PiSignInExtensionSource
 */
import { createHash } from "node:crypto";

import { PI_EXTENSION_ENV } from "./PiLaunch.ts";

/** The sign-in command: `/threadlines-sign-in <nonce>`. */
export const PI_SIGN_IN_COMMAND = "threadlines-sign-in";

/** Every dialog title and notification of a sign-in: `<prefix><nonce>:<JSON>`. */
export const PI_SIGN_IN_PREFIX = "threadlines-sign-in:";

/** The groups the provider choice lists its options under. */
export const PI_SIGN_IN_GROUPS = {
  account: "Sign in with an account",
  apiKey: "Use an API key",
} as const;

export const PI_SIGN_IN_CHOICE_MESSAGE = "Choose what Pi connects to";

export const PI_SIGN_IN_EXTENSION_SOURCE = String.raw`// Threadlines sign-in extension for Pi. Generated by Threadlines; edits are replaced.
import { readFileSync, unlinkSync } from "node:fs";
import { getAgentDir, SettingsManager } from "@earendil-works/pi-coding-agent";
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

const SECRETS_ENV = ${JSON.stringify(PI_EXTENSION_ENV.secretsFile)};
const COMMAND = ${JSON.stringify(PI_SIGN_IN_COMMAND)};
const PREFIX = ${JSON.stringify(PI_SIGN_IN_PREFIX)};
const GROUPS = ${JSON.stringify(PI_SIGN_IN_GROUPS)};
const CHOICE_MESSAGE = ${JSON.stringify(PI_SIGN_IN_CHOICE_MESSAGE)};

type Option = { id: string; label: string; detail?: string; group?: string; configured?: boolean };
type Question = { kind: "choice" | "text" | "secret"; message: string; placeholder?: string; options?: Option[] };

// The nonce, from the file the environment names; the file is deleted once read.
function takeNonce(): string | undefined {
  const path = process.env[SECRETS_ENV];
  delete process.env[SECRETS_ENV];
  if (!path) return undefined;
  try {
    const value = JSON.parse(readFileSync(path, "utf8"));
    return typeof value?.nonce === "string" && value.nonce ? value.nonce : undefined;
  } catch {
    return undefined;
  } finally {
    try {
      unlinkSync(path);
    } catch {}
  }
}

// A typed key is only a key. Pi runs a stored key that starts with "!" as a
// command and reads "$NAME" as an environment variable; "$$" and "$!" are
// its escapes for the plain characters.
function literalKey(value: string): string {
  const escaped = value.replace(/\$/g, () => "$$");
  return escaped.startsWith("!") ? "$" + escaped : escaped;
}

function text(value: unknown): string | undefined {
  return typeof value === "string" && value.length > 0 ? value : undefined;
}

function errorText(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

export default function threadlinesSignIn(pi: ExtensionAPI) {
  const nonce = takeNonce();

  pi.registerCommand(COMMAND, {
    description: "Set by Threadlines",
    handler: async (args, ctx) => {
      if (!nonce || args.trim() !== nonce) return;
      const send = (message: Record<string, unknown>) =>
        ctx.ui.notify(PREFIX + nonce + ":" + JSON.stringify(message), "info");

      // Pi's ModelRuntime, behind the registry extensions get: what /login uses.
      const runtime = (ctx.modelRegistry as any)?.runtime;
      if (
        !runtime ||
        typeof runtime.login !== "function" ||
        typeof runtime.getProviders !== "function" ||
        typeof runtime.getProviderAuthStatus !== "function"
      ) {
        send({ type: "unsupported" });
        return;
      }

      let asked = 0;
      // Undefined when the user cancelled, or Pi took the question back.
      const ask = async (question: Question, signal?: AbortSignal): Promise<string | undefined> => {
        asked += 1;
        const id = String(asked);
        const title = PREFIX + nonce + ":" + JSON.stringify({ id, ...question });
        const options = signal ? { signal } : undefined;
        const answer =
          question.kind === "choice"
            ? await ctx.ui.select(title, (question.options ?? []).map((option) => option.id), options)
            : await ctx.ui.input(title, question.placeholder, options);
        // Pi's RPC drops an aborted dialog without a word to Threadlines.
        if (signal?.aborted) send({ type: "withdrawn", id });
        return typeof answer === "string" ? answer : undefined;
      };

      // Each with its provider's name, which orders the list as Pi's own /login does.
      const accounts: Array<[string, Option]> = [];
      const keys: Array<[string, Option]> = [];
      for (const provider of runtime.getProviders()) {
        const id = text(provider?.id);
        if (!id) continue;
        const name = text(provider.name) ?? id;
        let connected: "oauth" | "api_key" | undefined;
        try {
          if (runtime.getProviderAuthStatus(id)?.configured === true) {
            connected = runtime.isUsingOAuth?.(id) === true ? "oauth" : "api_key";
          }
        } catch {}
        const oauth = provider.auth?.oauth;
        if (oauth) {
          const label = text(oauth.name) ?? name;
          accounts.push([name, {
            id: "oauth:" + id,
            label,
            ...(label.startsWith(name) ? {} : { detail: name }),
            group: GROUPS.account,
            ...(connected === "oauth" ? { configured: true } : {}),
          }]);
        }
        const apiKey = provider.auth?.apiKey;
        // Keys Pi only finds in the environment or a cloud profile can't be entered here.
        if (apiKey && typeof apiKey.login === "function") {
          const keyName = text(apiKey.name);
          keys.push([name, {
            id: "api_key:" + id,
            label: name,
            ...(keyName && keyName !== name + " API key" ? { detail: keyName } : {}),
            group: GROUPS.apiKey,
            ...(connected === "api_key" ? { configured: true } : {}),
          }]);
        }
      }
      const byProvider = (a: [string, Option], b: [string, Option]) =>
        a[0].localeCompare(b[0]) || a[1].label.localeCompare(b[1].label);
      const choice = await ask({
        kind: "choice",
        message: CHOICE_MESSAGE,
        options: [...accounts.sort(byProvider), ...keys.sort(byProvider)].map(([, option]) => option),
      });
      if (!choice) {
        send({ type: "cancelled" });
        return;
      }
      const split = choice.indexOf(":");
      const type = choice.slice(0, split);
      const providerId = choice.slice(split + 1);
      const providerName = text(runtime.getProvider?.(providerId)?.name) ?? providerId;

      // The installation's id, as /login gives it (ChatGPT sign-in needs one).
      let settings: any;
      const getDeviceId = () => {
        const saved = text((pi.getSettings() as any)?.deviceId);
        if (saved) return saved;
        settings ??= SettingsManager.create(ctx.cwd, getAgentDir());
        return settings.getOrCreateDeviceId();
      };

      try {
        await runtime.login(
          providerId,
          type,
          {
            prompt: async (prompt: any) => {
              const kind = prompt.type === "select" ? "choice" : prompt.type === "secret" ? "secret" : "text";
              const answer = await ask(
                {
                  kind,
                  message: String(prompt.message ?? ""),
                  ...(text(prompt.placeholder) ? { placeholder: prompt.placeholder } : {}),
                  ...(prompt.type === "select"
                    ? {
                        options: (prompt.options ?? []).map((option: any) => ({
                          id: String(option.id),
                          label: String(option.label ?? option.id),
                          ...(text(option.description) ? { detail: option.description } : {}),
                        })),
                      }
                    : {}),
                },
                prompt.signal,
              );
              if (answer === undefined) throw new Error("Login cancelled");
              return type === "api_key" && prompt.type === "secret" ? literalKey(answer) : answer;
            },
            notify: (event: any) => {
              if (event?.type === "auth_url" && text(event.url)) {
                send({ type: "auth_url", url: event.url, ...(text(event.instructions) ? { instructions: event.instructions } : {}) });
              } else if (event?.type === "device_code" && text(event.userCode) && text(event.verificationUri)) {
                send({ type: "device_code", code: event.userCode, url: event.verificationUri });
              } else if ((event?.type === "info" || event?.type === "progress") && text(event.message)) {
                send({ type: event.type, message: event.message });
              }
            },
          },
          { getDeviceId },
        );
      } catch (error) {
        const message = errorText(error);
        send(message === "Login cancelled" ? { type: "cancelled" } : { type: "failed", message });
        return;
      }

      if (settings) {
        await settings.flush?.();
        const errors = settings.drainErrors?.() ?? [];
        if (errors.length > 0) {
          send({ type: "info", message: "Pi couldn't save its settings: " + errorText(errors[0]) });
        }
      }
      // Providers with a catalog per account (OpenRouter, Radius) list their models now.
      try {
        await runtime.refresh?.({ providers: [providerId], signal: AbortSignal.timeout(15000) });
      } catch {}
      send({ type: "done", provider: providerName, method: type });
    },
  });
}
`;

/** The extension's file name: its content's hash, so versions never collide. */
export function piSignInExtensionFileName(source: string = PI_SIGN_IN_EXTENSION_SOURCE): string {
  const digest = createHash("sha256").update(source).digest("hex").slice(0, 16);
  return `threadlines-pi-sign-in-${digest}.ts`;
}
