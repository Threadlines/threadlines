// @effect-diagnostics globalConsole:off nodeBuiltinImport:off
/**
 * Writes Pi's published model list (the pinned `@earendil-works/pi-ai`'s
 * `models.generated.js`) into `src/provider/pi/_generated/piModelCatalog.gen.ts`,
 * so telemetry can name a Pi model that Pi itself ships and keep a model a
 * user added in Pi's `models.json` or an extension hidden as custom.
 *
 *   node apps/server/scripts/generate-pi-model-catalog.ts
 *
 * Run it after updating `@earendil-works/pi-coding-agent`: the catalog test
 * fails until the copy matches the installed Pi.
 */
import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const serverRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
export const PI_MODEL_CATALOG_PATH = join(
  serverRoot,
  "src",
  "provider",
  "pi",
  "_generated",
  "piModelCatalog.gen.ts",
);

/** The installed pi-ai: a sibling of the pi-coding-agent the server pins. */
function installedPiAiDir(): string | undefined {
  const agent = join(serverRoot, "node_modules", "@earendil-works", "pi-coding-agent");
  if (!existsSync(agent)) return undefined;
  const piAi = join(dirname(realpathSync(agent)), "pi-ai");
  return existsSync(join(piAi, "dist", "models.generated.js")) ? piAi : undefined;
}

/**
 * Pi's published models as lowercased `provider/id` slugs (the form a Pi
 * model selection takes), with pi-ai's version. Undefined when Pi isn't installed.
 */
export async function readInstalledPiCatalog(): Promise<
  { readonly version: string; readonly slugs: ReadonlyArray<string> } | undefined
> {
  const dir = installedPiAiDir();
  if (!dir) return undefined;
  const { MODELS } = (await import(
    pathToFileURL(join(dir, "dist", "models.generated.js")).href
  )) as { MODELS: Record<string, Record<string, unknown>> };
  const { version } = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as {
    readonly version?: string;
  };
  const slugs = new Set<string>();
  for (const [provider, models] of Object.entries(MODELS)) {
    for (const id of Object.keys(models)) slugs.add(`${provider}/${id}`.toLowerCase());
  }
  return {
    version: version ?? "unknown",
    slugs: [...slugs].toSorted(),
  };
}

export function renderPiModelCatalog(catalog: {
  readonly version: string;
  readonly slugs: ReadonlyArray<string>;
}): string {
  return [
    "// This file is generated by apps/server/scripts/generate-pi-model-catalog.ts. Do not edit manually.",
    "",
    "/** The @earendil-works/pi-ai release the list below was read from. */",
    `export const PI_MODEL_CATALOG_VERSION = ${JSON.stringify(catalog.version)};`,
    "",
    "/** Every model Pi ships, as its lowercased `provider/id` slug. All public. */",
    "export const PI_PUBLIC_MODELS: ReadonlySet<string> = new Set([",
    ...catalog.slugs.map((slug) => `  ${JSON.stringify(slug)},`),
    "]);",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const catalog = await readInstalledPiCatalog();
  if (!catalog) {
    console.error("Pi isn't installed: run `vp install` first.");
    process.exit(1);
  }
  writeFileSync(PI_MODEL_CATALOG_PATH, renderPiModelCatalog(catalog));
  console.log(`Wrote ${catalog.slugs.length} Pi models (pi-ai ${catalog.version}).`);
}
