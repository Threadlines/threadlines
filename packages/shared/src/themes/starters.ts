export interface StarterTheme {
  /** Stable across releases: devices store a starter choice by this id. */
  readonly id: string;
  readonly manifest: ThemeManifest;
}

const starter = (
  id: string,
  manifest: Omit<ThemeManifest, "format" | "createdBy">,
): StarterTheme => ({
  id,
  manifest: { format: THEME_FILE_FORMAT, createdBy: { kind: "starter" }, ...manifest },
});

