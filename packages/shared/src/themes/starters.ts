/**
 * The starter themes that ship with Threadlines (docs/design/custom-themes.md,
 * "Starter themes"). Read-only: users duplicate one to change it. Each one's
 * colors are taken from its art, and each passes the readability table and
 * stays far under the backdrop budget (starters.test.ts, and
 * scripts/render-theme-thumbnails.ts measures them in a real browser).
 * Thumbnails live at apps/web/public/themes/<id>.png.
 */
