/**
 * The starter themes that ship with Threadlines (docs/design/custom-themes.md,
 * "Starter themes"). Read-only: users duplicate one to change it. Each one's
 * colors are taken from its art, and each passes the readability table and
 * stays far under the backdrop budget (starters.test.ts, and
 * scripts/render-theme-thumbnails.ts measures them in a real browser).
 * Thumbnails live at apps/web/public/themes/<id>.png.
 */
import { THEME_FILE_FORMAT, type ThemeManifest } from "@threadlines/contracts";

import {
  AURORA_ART,
  DUNES_ART,
  EMBER_ART,
  NIGHT_RAIN_ART,
  SNOWFIELD_ART,
} from "./backdropStarterArt.ts";

export interface StarterTheme {
  /** Stable across releases: devices store a starter choice by this id. */
  readonly id: string;
  readonly manifest: ThemeManifest;
}

const starter = (
  id: string,
  manifest: Omit<ThemeManifest, "format" | "createdBy">,
): StarterTheme => ({
  id,
  manifest: { format: THEME_FILE_FORMAT, createdBy: { kind: "starter" }, ...manifest },
});

