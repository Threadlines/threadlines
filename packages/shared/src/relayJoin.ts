import {
  RelayErrorResponse,
  type RelayJoinerDescription,
  RelayJoinResult,
  RelayRequestStatusResult,
} from "@threadlines/contracts/relay";
import * as Option from "effect/Option";
import * as Schema from "effect/Schema";

import {
  claimProof,
  claimSecrets,
  decodePublicKey,
  fromBase64Url,
  generateStoredKeyPair,
  type StoredKeyPair,
  toBase64Url,
} from "./relaySecure.ts";

/**
 * The joining side of a "Connect a device" invite claim (QR code, link, or a
 * computer link), shared by the web app and the server. Pure functions over
 * fetch and WebCrypto: whoever calls them stores the credentials.
 */

/** A host's invite as the joiner got it: from a QR code, a link, or another server. */
export interface RelayInviteLink {
  readonly relayOrigin: string;
  readonly hostId: string;
  readonly inviteId: string;
  readonly inviteSecret: string;
  /** The host's end-to-end key, pinned straight from the invite. */
  readonly hostPublicKey: string;
}

export class RelayRequestError extends Error {
  readonly status: number | null;
  readonly code: string | null;

  constructor(message: string, status: number | null, code: string | null) {
    super(message);
    this.status = status;
    this.code = code;
  }
}

const decodeErrorResponse = Schema.decodeUnknownOption(RelayErrorResponse);
const decodeJoinResult = Schema.decodeUnknownOption(RelayJoinResult);
const decodeRequestStatus = Schema.decodeUnknownOption(RelayRequestStatusResult);

export async function relayFetch<A>(
  url: string,
  init: RequestInit,
  decode: (value: unknown) => Option.Option<A>,
): Promise<A> {
  let response: Response;
  try {
    response = await fetch(url, init);
  } catch (error) {
    throw new RelayRequestError(
      `Couldn't reach the relay. ${error instanceof Error ? error.message : ""}`.trim(),
      null,
      "relay-unavailable",
    );
  }
  const body: unknown = await response.json().catch(() => null);
  if (!response.ok) {
    const parsed = decodeErrorResponse(body);
    throw new RelayRequestError(
      Option.isSome(parsed)
        ? parsed.value.error
        : `The relay answered with HTTP ${response.status}.`,
      response.status,
      Option.isSome(parsed) ? (parsed.value.code ?? null) : null,
    );
  }
  const decoded = decode(body);
  if (Option.isNone(decoded)) {
    throw new RelayRequestError("The relay sent an unexpected answer.", response.status, null);
  }
  return decoded.value;
}

/** 32 random bytes, URL-safe. Generated by the joiner; only its hash leaves the device. */
export function generateRelaySecret(): string {
  const bytes = new Uint8Array(32);
  crypto.getRandomValues(bytes);
  return toBase64Url(bytes);
}

export async function relaySecretHash(secret: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(secret));
  return toBase64Url(new Uint8Array(digest));
}

export interface RelayJoinSecrets {
  readonly joinId: string;
  readonly deviceSecretHash: string;
  readonly requestSecretHash: string;
  readonly devicePublicKey: string;
  readonly joiner: RelayJoinerDescription;
}

export function postRelayInviteClaim(
  invite: Pick<RelayInviteLink, "relayOrigin" | "hostId" | "inviteId">,
  input: RelayJoinSecrets & { readonly claimToken: string; readonly claimProof: string },
): Promise<RelayJoinResult> {
  return relayFetch(
    new URL(
      `/v2/hosts/${encodeURIComponent(invite.hostId)}/invites/${encodeURIComponent(invite.inviteId)}/claim`,
      invite.relayOrigin,
    ).toString(),
    {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify(input),
    },
    decodeJoinResult,
  );
}

function requestUrl(
  input: {
    readonly relayOrigin: string;
    readonly hostId: string;
    readonly requestId: string;
  },
  suffix = "",
): string {
  return new URL(
    `/v2/hosts/${encodeURIComponent(input.hostId)}/requests/${encodeURIComponent(input.requestId)}${suffix}`,
    input.relayOrigin,
  ).toString();
}

export function getRelayRequestStatus(input: {
  readonly relayOrigin: string;
  readonly hostId: string;
  readonly requestId: string;
  readonly requestSecret: string;
}) {
  return relayFetch(
    requestUrl(input),
    { headers: { authorization: `Bearer ${input.requestSecret}` } },
    decodeRequestStatus,
  );
}

/** Sends the joiner's nonce, once it has the computer's (code joins only). */
export function postRelayReveal(input: {
  readonly relayOrigin: string;
  readonly hostId: string;
  readonly requestId: string;
  readonly requestSecret: string;
  readonly deviceNonce: string;
}) {
  return relayFetch(
    requestUrl(input, "/reveal"),
    {
      method: "POST",
      headers: {
        authorization: `Bearer ${input.requestSecret}`,
        "content-type": "application/json",
      },
      body: JSON.stringify({ deviceNonce: input.deviceNonce }),
    },
    decodeRequestStatus,
  );
}

export function cancelRelayRequest(input: {
  readonly relayOrigin: string;
  readonly hostId: string;
  readonly requestId: string;
  readonly requestSecret: string;
}) {
  return relayFetch(
    requestUrl(input, "/cancel"),
    { method: "POST", headers: { authorization: `Bearer ${input.requestSecret}` } },
    decodeRequestStatus,
  );
}

function isUnreachable(error: unknown): boolean {
  return (
    error instanceof RelayRequestError &&
    (error.status === null || error.code === "relay-unavailable")
  );
}

/**
 * Retries a join once with the same ids when the relay couldn't be reached:
 * if the first attempt did land, the relay returns that same request instead
 * of answering "busy".
 */
export async function withRelayReplay<A>(send: () => Promise<A>): Promise<A> {
  try {
    return await send();
  } catch (error) {
    if (!isUnreachable(error)) throw error;
    return await send();
  }
}

/** A claimed invite: the relay's request, and what the joiner must keep to use it. */
export interface RelayInviteClaim {
  readonly accepted: RelayJoinResult & { readonly relayOrigin: string };
  readonly credentials: { readonly deviceSecret: string; readonly deviceKey: StoredKeyPair };
  readonly requestSecret: string;
  readonly hostPublicKey: string;
}

/** Thrown for an invite that can't be claimed as given (missing secret or key). */
export class RelayInviteInvalidError extends Error {}

/**
 * Claims a QR / link invite: makes this device's secrets and key, proves it
 * holds the invite secret, and sends the claim to the relay. The host
 * approves these on its own, so the wait for the answer is short. Throws
 * {@link RelayRequestError} with the relay's code, or
 * {@link RelayInviteInvalidError}.
 */
export async function claimRelayInvite(input: {
  readonly invite: RelayInviteLink;
  readonly joiner: RelayJoinerDescription;
}): Promise<RelayInviteClaim> {
  const inviteSecret = fromBase64Url(input.invite.inviteSecret);
  const hostKey = await decodePublicKey(input.invite.hostPublicKey);
  if (!inviteSecret || !hostKey) {
    throw new RelayInviteInvalidError("That link is incomplete. Scan the code again.");
  }
  const joinId = crypto.randomUUID();
  const deviceSecret = generateRelaySecret();
  const requestSecret = generateRelaySecret();
  const deviceSecretHash = await relaySecretHash(deviceSecret);
  const requestSecretHash = await relaySecretHash(requestSecret);
  const deviceKey = await generateStoredKeyPair();
  const { claimToken, macKey } = await claimSecrets(inviteSecret);
  const proof = await claimProof({
    macKey,
    inviteId: input.invite.inviteId,
    joinId,
    devicePublicKey: fromBase64Url(deviceKey.publicKey)!,
  });
  const result = await withRelayReplay(() =>
    postRelayInviteClaim(input.invite, {
      joinId,
      deviceSecretHash,
      requestSecretHash,
      devicePublicKey: deviceKey.publicKey,
      claimToken,
      claimProof: proof,
      joiner: input.joiner,
    }),
  );
  return {
    accepted: { ...result, relayOrigin: input.invite.relayOrigin },
    credentials: { deviceSecret, deviceKey },
    requestSecret,
    hostPublicKey: input.invite.hostPublicKey,
  };
}

/** The relay WebSocket URL a device connects to its computer through. */
export function relayDeviceSocketUrl(input: {
  readonly relayOrigin: string;
  readonly hostId: string;
  readonly deviceId: string;
}): string {
  const url = new URL(
    `/v2/hosts/${encodeURIComponent(input.hostId)}/devices/${encodeURIComponent(input.deviceId)}/connect`,
    input.relayOrigin,
  );
  url.protocol = url.protocol === "https:" ? "wss:" : "ws:";
  return url.toString();
}
